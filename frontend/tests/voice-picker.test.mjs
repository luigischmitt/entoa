import assert from "node:assert/strict";
import test from "node:test";
import { DEFAULT_INTERVIEWER_VOICE, INTERVIEWER_VOICE_OPTIONS } from "../src/lib/interview/voices.mjs";
import { groupVoicesByGender, interviewerVoiceStorageKey, readStoredInterviewerVoice, storeInterviewerVoice, voiceDisplayName, voiceSamplePath, voiceSummary, voiceTraits } from "../src/lib/interview/voice-picker.mjs";
import { DEFAULT_INTERVIEWER_SPEECH_SPEED, formatInterviewerSpeechSpeed, interviewerSpeechSpeedStorageKey, readStoredInterviewerSpeechSpeed, resolveInterviewerSpeechSpeed, stepInterviewerSpeechSpeed, storeInterviewerSpeechSpeed } from "../src/lib/interview/interviewer-speech-speed.mjs";

const memoryStorage = () => {
  const map = new Map();
  return { getItem: (k) => map.get(k) ?? null, setItem: (k, v) => map.set(k, v), removeItem: (k) => map.delete(k), map };
};

test("display names come from the id and traits are in Portuguese", () => {
  assert.equal(voiceDisplayName("en-US-AndrewNeural"), "Andrew");
  assert.equal(voiceDisplayName("en-GB-SoniaNeural"), "Sonia");
  assert.equal(voiceTraits({ gender: "male", accent: "US" }), "masculina, americana");
  assert.equal(voiceTraits({ gender: "female", accent: "UK" }), "feminina, britânica");
  assert.equal(voiceSummary("en-US-AndrewNeural"), "Andrew · masculina, americana");
  assert.equal(voiceSummary("en-GB-SoniaNeural"), "Sonia · feminina, britânica");
  assert.equal(voiceSummary("unknown"), "Andrew · masculina, americana");
});

test("voices are grouped by gender, cover every option once and flag the default", () => {
  const groups = groupVoicesByGender();
  assert.deepEqual(groups.map((group) => group.label), ["Masculinas", "Femininas"]);
  const ids = groups.flatMap((group) => group.voices.map((voice) => voice.id));
  assert.deepEqual([...ids].sort(), INTERVIEWER_VOICE_OPTIONS.map((voice) => voice.id).sort());
  assert.deepEqual(groups.flatMap((group) => group.voices).filter((voice) => voice.isDefault).map((voice) => voice.id), [DEFAULT_INTERVIEWER_VOICE]);
  assert.ok(groups[0].voices.every((voice) => voice.gender === "male"));
  assert.ok(groups[1].voices.every((voice) => voice.gender === "female"));
});

test("every voice has a stable static sample path generated by the Azure sample script", () => {
  for (const voice of INTERVIEWER_VOICE_OPTIONS) {
    const path = voiceSamplePath(voice.id);
    assert.equal(path, `/voices/${voice.id}.mp3`);
  }
  assert.equal(voiceSamplePath("nope"), `/voices/${DEFAULT_INTERVIEWER_VOICE}.mp3`);
});

test("the choice persists per browser; the default clears it and bad values are ignored", () => {
  const storage = memoryStorage();
  assert.equal(readStoredInterviewerVoice(storage), DEFAULT_INTERVIEWER_VOICE);
  assert.equal(storeInterviewerVoice(storage, "en-GB-SoniaNeural"), true);
  assert.equal(storage.map.get(interviewerVoiceStorageKey), "en-GB-SoniaNeural");
  assert.equal(readStoredInterviewerVoice(storage), "en-GB-SoniaNeural");
  storage.setItem(interviewerVoiceStorageKey, "garbage");
  assert.equal(readStoredInterviewerVoice(storage), DEFAULT_INTERVIEWER_VOICE);
  storeInterviewerVoice(storage, "en-US-AvaNeural");
  storeInterviewerVoice(storage, DEFAULT_INTERVIEWER_VOICE);
  assert.equal(storage.map.has(interviewerVoiceStorageKey), false);
  const broken = { getItem() { throw new Error("blocked"); }, setItem() { throw new Error("blocked"); }, removeItem() { throw new Error("blocked"); } };
  assert.equal(readStoredInterviewerVoice(broken), DEFAULT_INTERVIEWER_VOICE);
  assert.equal(storeInterviewerVoice(broken, "en-GB-SoniaNeural"), false);
});

test("speech speed persists per browser and falls back safely", () => {
  const storage = memoryStorage();
  assert.equal(readStoredInterviewerSpeechSpeed(storage), DEFAULT_INTERVIEWER_SPEECH_SPEED);
  assert.equal(storeInterviewerSpeechSpeed(storage, 0.9), true);
  assert.equal(storage.map.get(interviewerSpeechSpeedStorageKey), "0.9");
  assert.equal(readStoredInterviewerSpeechSpeed(storage), 0.9);
  storage.setItem(interviewerSpeechSpeedStorageKey, "0.85");
  assert.equal(readStoredInterviewerSpeechSpeed(storage), 0.85);
  storage.setItem(interviewerSpeechSpeedStorageKey, "abc");
  assert.equal(readStoredInterviewerSpeechSpeed(storage), DEFAULT_INTERVIEWER_SPEECH_SPEED);
  storeInterviewerSpeechSpeed(storage, 1);
  assert.equal(storage.map.has(interviewerSpeechSpeedStorageKey), false);
});

test("speech speed accepts custom values inside 0.7–1.3 in 0.05 steps", () => {
  assert.equal(resolveInterviewerSpeechSpeed(0.85), 0.85);
  assert.equal(resolveInterviewerSpeechSpeed(0.87), 0.85);
  assert.equal(resolveInterviewerSpeechSpeed(0.5), 0.7);
  assert.equal(resolveInterviewerSpeechSpeed(2), 1.3);
  assert.equal(resolveInterviewerSpeechSpeed(Number.NaN), 1);
  assert.equal(resolveInterviewerSpeechSpeed(undefined), 1);
  assert.equal(stepInterviewerSpeechSpeed(1, -1), 0.95);
  assert.equal(stepInterviewerSpeechSpeed(0.7, -1), 0.7);
  assert.equal(stepInterviewerSpeechSpeed(1.25, 1), 1.3);
  assert.equal(formatInterviewerSpeechSpeed(0.85), "0,85×");
  assert.equal(formatInterviewerSpeechSpeed(0.9, "en"), "0.9×");
  assert.equal(formatInterviewerSpeechSpeed(1), "1×");
});
